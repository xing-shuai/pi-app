import { act, cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import type { LocalFolderBrowseResult } from '@shared/local-folder-types'
import { LocalFolderDialog, localFolderBreadcrumbs } from './local-folder-dialog'

const directory = (path = '/home/me'): LocalFolderBrowseResult => ({ path, home: '/home/me', parent: path === '/' ? null : path.slice(0, path.lastIndexOf('/')) || '/', roots: [{ name: 'Filesystem', path: '/' }], entries: [{ name: 'project', path: `${path}/project`, directory: true }, { name: 'work', path: `${path}/work`, directory: true }], truncated: false })
const deferred = <T,>() => { let resolve!: (value: T) => void; const promise = new Promise<T>((done) => { resolve = done }); return { promise, resolve } }
beforeEach(() => { vi.spyOn(HTMLElement.prototype, 'getClientRects').mockReturnValue([{}] as unknown as DOMRectList) })
afterEach(() => { cleanup(); vi.restoreAllMocks() })

function setup(extra: Partial<Parameters<typeof LocalFolderDialog>[0]> = {}) {
  const props = { browse: vi.fn(async ({ path }) => directory(path === '~' ? '/home/me' : path)), resolve: vi.fn(async (path: string) => ({ path, name: 'me' })), onSelect: vi.fn(), onClose: vi.fn(), ...extra }
  return { ...render(<LocalFolderDialog {...props} />), ...props }
}
describe('app-themed Local folder selector', () => {
  it('loads HOME, offers roots/recent shortcuts, navigates with Go/Parent/breadcrumbs and only canonicalizes on Select', async () => {
    const props = setup({ recentPaths: ['/code/recent', '/__pi_ssh__/host/project'] })
    const input = screen.getByRole('textbox', { name: 'Local folder path' })
    expect(input).toHaveFocus()
    await screen.findByRole('button', { name: 'project' })
    expect(props.browse).toHaveBeenCalledWith({ path: '~', includeHidden: false })
    expect(screen.queryByText('/__pi_ssh__/host/project')).not.toBeInTheDocument()
    fireEvent.change(input, { target: { value: '/code' } })
    expect(props.browse).toHaveBeenCalledTimes(1)
    expect(screen.getByRole('button', { name: 'Select folder' })).toBeDisabled()
    fireEvent.submit(input.closest('form')!)
    await waitFor(() => expect(input).toHaveValue('/code'))
    await waitFor(() => expect(screen.getByRole('button', { name: 'Select folder' })).toBeEnabled())
    expect(props.browse).toHaveBeenLastCalledWith({ path: '/code', includeHidden: false })
    fireEvent.click(screen.getByRole('button', { name: 'project' }))
    await waitFor(() => expect(input).toHaveValue('/code/project'))
    fireEvent.click(screen.getByRole('button', { name: 'Parent' }))
    await waitFor(() => expect(input).toHaveValue('/code'))
    fireEvent.click(within(screen.getByRole('navigation', { name: 'Local folder breadcrumb' })).getByRole('button', { name: '/' }))
    await waitFor(() => expect(input).toHaveValue('/'))
    expect(screen.getByRole('button', { name: 'Parent' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: '/code/recent' }))
    await waitFor(() => expect(input).toHaveValue('/code/recent'))
    expect(props.resolve).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Select folder' }))
    await waitFor(() => expect(props.onSelect).toHaveBeenCalledWith('/code/recent'))
    expect(props.resolve).toHaveBeenCalledWith('/code/recent')
  })
  it('loads hidden folders explicitly, handles errors/retry, and announces truncation', async () => {
    const browse = vi.fn().mockRejectedValueOnce(new Error('Permission denied.')).mockResolvedValue({ ...directory(), truncated: true })
    setup({ browse })
    expect(await screen.findByRole('alert')).toHaveTextContent('Permission denied.')
    expect(screen.getByRole('button', { name: 'Select folder' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: 'Go' }))
    await screen.findByText(/Showing the first 500/)
    fireEvent.click(screen.getByRole('checkbox', { name: 'Show hidden folders' }))
    await waitFor(() => expect(browse).toHaveBeenLastCalledWith({ path: '/home/me', includeHidden: true }))
  })
  it('prevents stale browsing responses from overwriting a newer path', async () => {
    const old = deferred<LocalFolderBrowseResult>(), next = deferred<LocalFolderBrowseResult>()
    const browse = vi.fn().mockReturnValueOnce(old.promise).mockReturnValueOnce(next.promise)
    setup({ browse })
    const input = screen.getByRole('textbox', { name: 'Local folder path' })
    expect(screen.getByRole('status')).toHaveTextContent('Reading local folders')
    fireEvent.change(input, { target: { value: '/new' } })
    fireEvent.click(screen.getByRole('button', { name: 'Go' }))
    await act(async () => { next.resolve(directory('/new')) })
    await act(async () => { old.resolve(directory('/stale')) })
    expect(input).toHaveValue('/new')
    expect(within(screen.getByRole('navigation', { name: 'Local folder breadcrumb' })).getByRole('button', { name: 'new' })).toBeInTheDocument()
  })
  it('does not overwrite path edits with a pending HOME response and ignores unmounted browsing', async () => {
    const pending = deferred<LocalFolderBrowseResult>()
    const props = setup({ browse: vi.fn(() => pending.promise) })
    const input = screen.getByRole('textbox', { name: 'Local folder path' })
    fireEvent.change(input, { target: { value: '/typed-but-not-submitted' } })
    await act(async () => { pending.resolve(directory('/home/me')) })
    expect(input).toHaveValue('/typed-but-not-submitted')
    expect(screen.getByRole('button', { name: 'Select folder' })).toBeDisabled()
    props.unmount()
    const late = deferred<LocalFolderBrowseResult>()
    const next = setup({ browse: vi.fn(() => late.promise) })
    next.unmount()
    await act(async () => { late.resolve(directory('/late')) })
    expect(next.onSelect).not.toHaveBeenCalled()
  })
  it('cancels immediately during resolve, discards late results, and does not fall back after an IPC failure', async () => {
    const pending = deferred<{ path: string; name: string }>()
    const props = setup({ resolve: vi.fn(() => pending.promise) })
    fireEvent.click(await screen.findByRole('button', { name: 'project' }))
    await waitFor(() => expect(screen.getByRole('button', { name: 'Select folder' })).toBeEnabled())
    fireEvent.click(screen.getByRole('button', { name: 'Select folder' }))
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))
    expect(props.onClose).toHaveBeenCalledOnce()
    await act(async () => { pending.resolve({ path: '/late', name: 'late' }) })
    expect(props.onSelect).not.toHaveBeenCalled()
    props.unmount()
    const fail = setup({ resolve: vi.fn().mockRejectedValue(new Error('Folder was removed.')) })
    await screen.findByRole('button', { name: 'project' })
    fireEvent.click(screen.getByRole('button', { name: 'Select folder' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Folder was removed.')
    expect(fail.onSelect).not.toHaveBeenCalled(); expect(fail.onClose).not.toHaveBeenCalled()
  })
  it('supports arrows, focus trap, Escape cancellation, and restores prior focus', async () => {
    const prior = document.createElement('button'); document.body.append(prior); prior.focus()
    const props = setup()
    const first = await screen.findByRole('button', { name: 'project' })
    first.focus(); fireEvent.keyDown(first, { key: 'ArrowDown' })
    expect(screen.getByRole('button', { name: 'work' })).toHaveFocus()
    fireEvent.keyDown(document.activeElement!, { key: 'Home' }); expect(first).toHaveFocus()
    const select = screen.getByRole('button', { name: 'Select folder' })
    select.focus(); fireEvent.keyDown(select, { key: 'Tab' })
    expect(screen.getByRole('button', { name: 'Close Select local folder' })).toHaveFocus()
    fireEvent.keyDown(document.activeElement!, { key: 'Tab', shiftKey: true }); expect(select).toHaveFocus()
    fireEvent.keyDown(document, { key: 'Escape' }); expect(props.onClose).toHaveBeenCalledOnce()
    props.unmount(); expect(prior).toHaveFocus(); prior.remove()
  })
  it('uses native POSIX and Windows drive breadcrumbs, never virtualized paths', () => {
    expect(localFolderBreadcrumbs('/home/me')).toEqual([{ name: '/', path: '/' }, { name: 'home', path: '/home' }, { name: 'me', path: '/home/me' }])
    expect(localFolderBreadcrumbs('C:\\Users\\Dev')).toEqual([{ name: 'C:\\', path: 'C:\\' }, { name: 'Users', path: 'C:\\Users' }, { name: 'Dev', path: 'C:\\Users\\Dev' }])
    expect(localFolderBreadcrumbs('D:\\')).toEqual([{ name: 'D:\\', path: 'D:\\' }])
  })
})
