import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { ReferenceModelMenu, placeModelMenus, placeModelSubmenu, quickModels } from './reference-model-menu'

const models = Array.from({ length: 240 }, (_, index) => ({ provider: index < 120 ? 'alpha' : 'beta', id: `model-${index}`, name: `Actual model ${index}`, available: true }))
const setup = () => {
  const onClose = vi.fn()
  const onPick = vi.fn()
  render(<><button data-model-anchor>Model trigger</button><ReferenceModelMenu models={models} current="alpha/model-2" recents={['beta/model-122', 'deleted/model']} pending={null} loading={false} anchorSelector="[data-model-anchor]" label="Choose model" onClose={onClose} onPick={onPick} /></>)
  return { onClose, onPick }
}
afterEach(() => { vi.useRealTimers(); document.documentElement.style.zoom = '' })

describe('reference model menu', () => {
  it('uses real current/recent/catalog metadata with no fabricated default claims', () => {
    expect(quickModels(models, 'alpha/model-2', ['deleted/model', 'beta/model-122']).map((row) => row.id)).toEqual(['model-2', 'model-122', 'model-0', 'model-1'])
    expect(quickModels(models, 'gone/current', [])[0]).toEqual({ provider: 'gone', id: 'current', available: false })
    setup()
    expect(screen.getByRole('button', { name: /Actual model 2 — alpha/ })).toHaveAttribute('aria-pressed', 'true')
    expect(screen.queryByText('Default')).toBeNull()
    expect(screen.getAllByRole('button')).toHaveLength(6)
  })
  it('keeps the catalog bounded, expands providers, and finds every model through search', async () => {
    const { onPick } = setup()
    fireEvent.click(screen.getByRole('button', { name: 'More models' }))
    const child = await screen.findByRole('dialog', { name: 'All models' })
    expect(within(child).queryByRole('button', { name: /Actual model/ })).toBeNull()
    fireEvent.click(within(child).getByRole('button', { name: /alpha/ }))
    expect(within(child).getAllByRole('button', { name: /Actual model/ })).toHaveLength(60)
    fireEvent.click(within(child).getByRole('button', { name: 'Show more results' }))
    expect(within(child).getAllByRole('button', { name: /Actual model/ })).toHaveLength(120)
    fireEvent.change(screen.getByRole('textbox', { name: 'Search models' }), { target: { value: 'Actual model 239' } })
    fireEvent.click(within(child).getByRole('button', { name: /Actual model 239/ }))
    expect(onPick).toHaveBeenCalledWith(models[239])
  })
  it('handles root Home/End/arrows, Right, nested Escape, Left and focus restoration', async () => {
    const { onClose } = setup()
    const root = screen.getByRole('dialog', { name: 'Choose model' })
    fireEvent.keyDown(root, { key: 'End' })
    expect(screen.getByRole('button', { name: 'More models' })).toHaveFocus()
    fireEvent.keyDown(root, { key: 'Home' })
    expect(screen.getByRole('button', { name: /Actual model 2 — alpha/ })).toHaveFocus()
    fireEvent.keyDown(root, { key: 'ArrowDown' })
    expect(screen.getByRole('button', { name: /Actual model 122/ })).toHaveFocus()
    fireEvent.keyDown(root, { key: 'ArrowRight' })
    const search = await screen.findByRole('textbox', { name: 'Search models' })
    fireEvent.keyDown(search, { key: 'Home' })
    fireEvent.keyDown(search, { key: 'Enter' })
    expect(screen.getByRole('button', { name: /alpha 120/ })).toHaveAttribute('aria-expanded', 'true')
    fireEvent.keyDown(search, { key: 'ArrowLeft' })
    expect(screen.queryByRole('dialog', { name: 'All models' })).toBeNull()
    fireEvent.keyDown(root, { key: 'ArrowRight' })
    await screen.findByRole('textbox', { name: 'Search models' })
    fireEvent.keyDown(window, { key: 'Escape' })
    expect(onClose).not.toHaveBeenCalled()
    expect(screen.getByRole('button', { name: 'More models' })).toHaveFocus()
    fireEvent.keyDown(window, { key: 'Escape' })
    expect(onClose).toHaveBeenCalledOnce()
    expect(screen.getByRole('button', { name: 'Model trigger' })).toHaveFocus()
  })
  it('opens on hover intent and stays open across the inter-pane gap', async () => {
    setup()
    const more = screen.getByRole('button', { name: 'More models' })
    vi.useFakeTimers()
    fireEvent.pointerEnter(more)
    act(() => vi.advanceTimersByTime(80))
    expect(screen.queryByRole('dialog', { name: 'All models' })).toBeNull()
    act(() => vi.advanceTimersByTime(80))
    fireEvent.pointerLeave(more)
    fireEvent.pointerMove(document.body)
    vi.useRealTimers()
    await waitFor(() => expect(screen.getByRole('dialog', { name: 'All models' })).toBeTruthy())
  })
  it('flips beside the primary and clamps at zoom without applying DPR twice', () => {
    const viewport = { width: 1200, height: 800 }
    expect(placeModelSubmenu({ left: 850, right: 1138, bottom: 700 }, viewport).side).toBe('left')
    expect(placeModelSubmenu({ left: 20, right: 308, bottom: 700 }, viewport).side).toBe('right')
    const zoomed = placeModelSubmenu({ left: 10, right: 350, bottom: 700 }, { width: 400, height: 800 }, 1.5)
    expect(zoomed.left * 1.5).toBeGreaterThanOrEqual(8)
    expect((zoomed.left + zoomed.width) * 1.5).toBeLessThanOrEqual(392)
    expect(zoomed.maxHeight * 1.5).toBeLessThanOrEqual(692)
    expect(placeModelMenus({ right: 399, top: 600 }, { width: 400, height: 800 }, 1.5).left).toBeGreaterThanOrEqual(8 / 1.5)
    const nearTop = placeModelMenus({ right: 399, top: 20, bottom: 48 }, { width: 400, height: 800 }, 1.5)
    expect(nearTop.top).toBe(54 / 1.5)
    expect(nearTop.bottom).toBeUndefined()
    expect(nearTop.maxHeight).toBeGreaterThan(160)
    // DOMRect and innerWidth are already CSS pixels at any devicePixelRatio.
    const before = placeModelSubmenu({ left: 850, right: 1138, bottom: 700 }, viewport, 1.25)
    vi.stubGlobal('devicePixelRatio', 2)
    expect(placeModelSubmenu({ left: 850, right: 1138, bottom: 700 }, viewport, 1.25)).toEqual(before)
    vi.unstubAllGlobals()
  })
})
