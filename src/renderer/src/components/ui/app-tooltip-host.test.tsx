import { act, cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { AppTooltipHost, computeAppTooltipPosition, hideAllAppTooltips, placeAppTooltip } from './app-tooltip-host'
import { DelayedTooltip, hideAllDelayedTooltips, wireDelayedTooltip } from '../../features/composer/delayed-tooltip'

async function tick(ms = 500) { await act(async () => { vi.advanceTimersByTime(ms) }) }
async function mutations() { await act(async () => { await Promise.resolve() }) }
beforeEach(() => vi.useFakeTimers())
afterEach(async () => {
  await act(async () => { hideAllAppTooltips() })
  cleanup()
  document.body.replaceChildren()
  document.documentElement.style.zoom = ''
  vi.useRealTimers()
})

it('opts in explicitly, renders plain text, and preserves accessible identity/descriptions', async () => {
  render(<><AppTooltipHost /><button data-app-tooltip={'<b>Details</b>'} aria-describedby="existing" aria-label="Identity" title="Untouched">Button</button><button title="Native">Native</button></>)
  const button = screen.getByText('Button')
  fireEvent.pointerOver(screen.getByText('Native'))
  await tick()
  expect(screen.queryByRole('tooltip')).toBeNull()
  fireEvent.pointerOver(button)
  await tick(499)
  expect(screen.queryByRole('tooltip')).toBeNull()
  await tick(1)
  const bubble = screen.getByRole('tooltip')
  expect(bubble.textContent).toBe('<b>Details</b>')
  expect(bubble.querySelector('b')).toBeNull()
  expect(button).toHaveAttribute('aria-label', 'Identity')
  expect(button).toHaveAttribute('title', 'Untouched')
  expect(button.getAttribute('aria-describedby')).toBe(`existing ${bubble.id}`)
  button.setAttribute('aria-describedby', `${button.getAttribute('aria-describedby')} later`)
  fireEvent.pointerOut(button)
  await mutations()
  expect(screen.queryByRole('tooltip')).toBeNull()
  expect(button).toHaveAttribute('aria-describedby', 'existing later')
})

it.each(['pointerdown', 'click', 'scroll', 'blur', 'resize', 'Escape', 'focusout'])('dismisses on %s without consuming events', async event => {
  render(<><AppTooltipHost /><button data-app-tooltip="Help">Button</button></>)
  const button = screen.getByRole('button')
  fireEvent.focusIn(button)
  await tick(80)
  expect(screen.getByRole('tooltip')).toBeTruthy()
  const listener = vi.fn()
  document.addEventListener('click', listener, { once: true })
  if (event === 'Escape') fireEvent.keyDown(button, { key: 'Escape' })
  else if (event === 'blur' || event === 'resize') fireEvent(window, new Event(event))
  else fireEvent(button, new Event(event, { bubbles: true }))
  await mutations()
  expect(screen.queryByRole('tooltip')).toBeNull()
  if (event === 'click') expect(listener).toHaveBeenCalled()
  document.removeEventListener('click', listener)
})

it('accelerates a pending hover on keyboard focus and hides when the marker is removed', async () => {
  render(<><AppTooltipHost /><button data-app-tooltip="Help">Button</button></>)
  const target = screen.getByRole('button')
  fireEvent.pointerOver(target)
  await tick(100)
  fireEvent.focusIn(target)
  await tick(80)
  expect(screen.getByRole('tooltip')).toHaveTextContent('Help')
  target.removeAttribute('data-app-tooltip')
  await mutations()
  expect(screen.queryByRole('tooltip')).toBeNull()
})

it('cancels pending shows and never reuses stale nested/empty content', async () => {
  render(<><AppTooltipHost /><div data-app-tooltip="Parent">Parent<span data-app-tooltip="">Empty</span><span data-app-tooltip="Child">Child</span></div></>)
  fireEvent.pointerOver(screen.getByText('Parent'))
  await tick(200)
  fireEvent.scroll(window)
  await tick()
  expect(screen.queryByRole('tooltip')).toBeNull()
  fireEvent.pointerOver(screen.getByText('Parent'))
  await tick()
  fireEvent.pointerOver(screen.getByText('Empty'))
  await tick()
  expect(screen.queryByRole('tooltip')).toBeNull()
  fireEvent.pointerOver(screen.getByText('Child'))
  await tick()
  expect(screen.getByRole('tooltip')).toHaveTextContent('Child')
})

it('handles disabled targets, removal, content changes, and menu opening', async () => {
  render(<><AppTooltipHost /><button disabled data-app-tooltip="Disabled help">Button</button></>)
  const target = screen.getByRole('button')
  fireEvent.pointerOver(target)
  await tick()
  expect(screen.getByRole('tooltip')).toHaveTextContent('Disabled help')
  target.setAttribute('data-app-tooltip', '')
  await mutations()
  expect(screen.queryByRole('tooltip')).toBeNull()
  target.setAttribute('data-app-tooltip', 'Again')
  fireEvent.pointerOver(target)
  await tick()
  const menu = document.createElement('div')
  menu.setAttribute('role', 'menu')
  document.body.appendChild(menu)
  await mutations()
  expect(screen.queryByRole('tooltip')).toBeNull()
  menu.remove()
  fireEvent.pointerOver(target)
  await tick()
  const parent = target.parentElement!
  target.remove()
  await mutations()
  expect(screen.queryByRole('tooltip')).toBeNull()
  expect(target).not.toHaveAttribute('aria-describedby')
  // Restore React-owned DOM before its cleanup; removal itself is what is under test.
  parent.appendChild(target)
})

it('shares one visible tooltip and close-all between global, wrapper, and DOM chips', async () => {
  render(<><AppTooltipHost /><button data-app-tooltip="Global">Global</button><DelayedTooltip content="Wrapper"><button>Chip</button></DelayedTooltip></>)
  fireEvent.pointerOver(screen.getByText('Global'))
  await tick()
  fireEvent.focusIn(screen.getByText('Chip'))
  await tick(80)
  expect(screen.getAllByRole('tooltip')).toHaveLength(1)
  expect(screen.getByRole('tooltip')).toHaveTextContent('Wrapper')
  const chip = document.createElement('span')
  document.body.appendChild(chip)
  const dispose = wireDelayedTooltip(chip, 'DOM')
  fireEvent.mouseEnter(chip)
  await tick()
  expect(screen.getAllByRole('tooltip')).toHaveLength(1)
  expect(screen.getByRole('tooltip')).toHaveTextContent('DOM')
  await act(async () => hideAllDelayedTooltips())
  expect(screen.queryByRole('tooltip')).toBeNull()
  fireEvent.mouseEnter(chip)
  chip.remove()
  await mutations()
  document.body.appendChild(chip)
  fireEvent.mouseEnter(chip)
  await tick()
  expect(screen.queryByRole('tooltip')).toBeNull()
  dispose?.()
})

it('suppresses chips during editing and all tooltips over modal dialogs', async () => {
  render(<><AppTooltipHost /><div contentEditable suppressContentEditableWarning tabIndex={0}><DelayedTooltip content="Path"><span>Chip</span></DelayedTooltip></div><button data-app-tooltip="Help">Button</button></>)
  const editor = document.querySelector('[contenteditable]') as HTMLElement
  editor.focus()
  fireEvent.pointerOver(screen.getByText('Chip'))
  await tick()
  expect(screen.queryByRole('tooltip')).toBeNull()
  editor.blur()
  const modal = document.createElement('div')
  modal.setAttribute('role', 'dialog')
  modal.setAttribute('aria-modal', 'true')
  document.body.appendChild(modal)
  fireEvent.pointerOver(screen.getByText('Button'))
  await tick()
  expect(screen.queryByRole('tooltip')).toBeNull()
})

describe('measured placement', () => {
  it.each([1, 5 / 6, 1.5])('centers actual dimensions and converts fixed coordinates at zoom %s', zoom => {
    const p = computeAppTooltipPosition({ left: 200, right: 240, top: 200, bottom: 220 }, { width: 60 * zoom, height: 30 * zoom }, { width: 600, height: 400 }, zoom)
    expect(p.left * zoom).toBeCloseTo(220 - 30 * zoom)
    expect(p.top * zoom).toBeCloseTo(200 - 38 * zoom)
  })
  it('flips below near top and clamps at viewport edges', () => {
    expect(computeAppTooltipPosition({ left: 0, right: 20, top: 2, bottom: 22 }, { width: 100, height: 40 }, { width: 300, height: 200 })).toEqual({ left: 8, top: 30 })
    expect(computeAppTooltipPosition({ left: 290, right: 300, top: 190, bottom: 200 }, { width: 100, height: 40 }, { width: 300, height: 200 })).toEqual({ left: 192, top: 142 })
  })
  it('uses measured width, caps viewport width, and suppresses NativeBrowserView overlap', () => {
    const anchor = document.createElement('button')
    const bubble = document.createElement('span')
    const native = document.createElement('div')
    native.setAttribute('data-browser-viewport', '')
    document.body.append(anchor, bubble, native)
    anchor.getBoundingClientRect = () => ({ left: 200, right: 240, top: 200, bottom: 220 }) as DOMRect
    bubble.getBoundingClientRect = () => ({ width: 60, height: 30 }) as DOMRect
    native.getBoundingClientRect = () => ({ left: 0, top: 0, right: 500, bottom: 500, width: 500, height: 500 }) as DOMRect
    expect(placeAppTooltip(anchor, bubble)).toBe(false)
    expect(bubble.style.left).toBe('190px')
    expect(bubble.style.visibility).toBe('hidden')
  })
})
