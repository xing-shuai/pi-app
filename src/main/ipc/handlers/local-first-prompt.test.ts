import { registerSessionHandlers } from './session'
import { registerWorkspaceHandlers } from './workspace'
import { registerPromptHandlers } from './prompt'
import { isPendingEphemeralSandboxDraft, setPendingEphemeralSandboxDraft, setPendingWorkerSessionFile } from '../../session-bind-state'
const call = (method: string, request: Record<string, unknown> = {}) => mocks.handlers.get(`ipc:${method}`)!(request)
beforeEach(() => {
  vi.clearAllMocks(); mocks.handlers.clear()
  setPendingEphemeralSandboxDraft(false); setPendingWorkerSessionFile(null)
  mocks.start.mockResolvedValue({ sessionId: 'first' }); mocks.newSession.mockResolvedValue({ sessionId: 'first', sessionFile: '/sessions/first.jsonl' })
  mocks.loadSession.mockResolvedValue({ sessionId: 'first', model: 'fixture/model' }); mocks.sendPrompt.mockResolvedValue(undefined)
  mocks.prepared.mockResolvedValue({ sessionId: 'first', sessionFile: '/sessions/first.jsonl', cwd: '/project' })
  registerSessionHandlers(); registerWorkspaceHandlers(); registerPromptHandlers()
})
it('leaves the ephemeral home draft when selecting a real local project and sends its first prompt', async () => {
  await call('session.setEphemeralDraft', { active: true })
  await expect(call('prompt.send', { text: 'must remain blocked' })).rejects.toThrow('EPHEMERAL_SANDBOX_DRAFT')
  await call('workspace.open', { path: '/project', awaitWorker: false })
  expect(isPendingEphemeralSandboxDraft()).toBe(false)
  // Reproduce a late old draft flag: materializing a real session is authoritative too.
  setPendingEphemeralSandboxDraft(true)
  await call('session.new', { workspaceId: '/project' })
  expect(isPendingEphemeralSandboxDraft()).toBe(false)
  await call('session.setPendingBind', { sessionFile: null })
  await expect(call('prompt.send', { text: 'first real local message', sessionFile: '/sessions/first.jsonl' })).resolves.toMatchObject({ model: 'fixture/model' })
  expect(mocks.sendPrompt).toHaveBeenCalledExactlyOnceWith('first real local message', '/sessions/first.jsonl')
})
it('does not clear the no-directory guard when session creation fails', async () => {
  setPendingEphemeralSandboxDraft(true)
  mocks.newSession.mockRejectedValueOnce(new Error('creation failed'))
  await expect(call('session.new', { workspaceId: '/project' })).rejects.toThrow('creation failed')
  expect(isPendingEphemeralSandboxDraft()).toBe(true)
  expect(mocks.sendPrompt).not.toHaveBeenCalled()
})
it('keeps preview-only/background work from changing the foreground draft, but clears it on explicit bind', async () => {
  setPendingEphemeralSandboxDraft(true)
  await call('workspace.ensureWorker', { path: '/project' })
  expect(isPendingEphemeralSandboxDraft()).toBe(true)
  await call('session.prepare', { sessionFile: '/sessions/first.jsonl', bind: false })
  expect(isPendingEphemeralSandboxDraft()).toBe(true)
  await call('session.prepare', { sessionFile: '/sessions/first.jsonl', bind: true })
  expect(isPendingEphemeralSandboxDraft()).toBe(false)
})
